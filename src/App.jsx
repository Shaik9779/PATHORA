import {
  BrowserRouter,
  Routes,
  Route,
  Navigate,
} from "react-router-dom";

import Home from "./pages/Home";
import Pathfinder from "./pages/Pathfinder";
import Practice from "./pages/Practice";
import Network from "./pages/Network";
import ResumeBuilder from "./pages/ResumeBuilder";
import Login from "./pages/Login";
import Signup from "./pages/Signup";
import Dashboard from "./pages/Dashboard";
import Opportunities from "./pages/Opportunities";
import Profile from "./pages/Profile";

import DashboardLayout from "./components/DashboardLayout";
import Footer from "./components/Footer";

function App() {
  return (
    <BrowserRouter>
      <Routes>
        {/* Public pages */}
        <Route
          path="/"
          element={
            <>
              <Home />
              <Footer />
            </>
          }
        />

        <Route
          path="/login"
          element={
            <>
              <Login />
              <Footer />
            </>
          }
        />

        <Route
          path="/signup"
          element={
            <>
              <Signup />
              <Footer />
            </>
          }
        />

        {/* Dashboard */}
        <Route
          path="/dashboard"
          element={
            <>
              <Dashboard />
              <Footer />
            </>
          }
        />

        {/* Dashboard workspace */}
        <Route element={<DashboardLayout />}>
          <Route
            path="/pathfinder"
            element={
              <>
                <Pathfinder />
                <Footer />
              </>
            }
          />

          <Route
            path="/practice"
            element={
              <>
                <Practice />
                <Footer />
              </>
            }
          />

          <Route
            path="/network"
            element={
              <>
                <Network />
                <Footer />
              </>
            }
          />

          <Route
            path="/resume-builder"
            element={
              <>
                <ResumeBuilder />
                <Footer />
              </>
            }
          />

          <Route
            path="/opportunities"
            element={
              <>
                <Opportunities />
                <Footer />
              </>
            }
          />

          <Route
            path="/profile"
            element={
              <>
                <Profile />
                <Footer />
              </>
            }
          />
        </Route>

        {/* Unknown paths */}
        <Route
          path="*"
          element={<Navigate to="/" replace />}
        />
      </Routes>
    </BrowserRouter>
  );
}

export default App;
